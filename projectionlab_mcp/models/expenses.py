"""
Plan-level expense events (plan.expenses.events[]).

Every type, field and default here was captured on 2026-09-13 by adding one expense of each
kind through the ProjectionLab 4.6 "New Expense" dialog (name + amount only, everything else
left at its default) and reading the record back with exportData(). The raw captures live in
docs/fixtures/expenses/. Models allow extra fields so nothing the app writes is dropped on a
round trip.

UI label -> stored `type` (and `subtype`):
  Living Expenses   living-expenses
  Rent              rent
  Debt              debt
  Student Loans     debt  (subtype "student-loans")
  Dependent         dependent-support
  Education         education
  Health Care       health-care
  Vacation          vacation
  Wedding           wedding
  Charity           charity
  Travel            travel
  Medical Expenses  medical
  Emergency         emergency
  Custom Expense    other
  (Medicare)        medicare  — generated by the app, never added by hand
"""
from __future__ import annotations

import uuid
from typing import Annotated, Any, Literal, Optional
from pydantic import BaseModel, Field

from .common import TimeRef


def _kw(value: str, modifier: str | None = None) -> TimeRef:
    return TimeRef(type="keyword", value=value, modifier=modifier)


class ExpenseYearlyChange(BaseModel):
    """How the expense amount changes year-over-year ("Change Over Time" in the UI).

    Observed `type` values and the UI label that produces them:
      "match-inflation"  Match Inflation            (default for most types)
      "none"             no change                  (default for once-off types and debt)
      "inflation+"       Inflation + N% per year    (default for health-care / medical, amount=2)
    Income and asset events additionally use "increase", "decrease", "match-inflation-plus",
    "appreciate", "depreciate".
    """
    model_config = {"extra": "allow"}

    type: str = "match-inflation"
    amount: float = 0
    amountType: str = "today$"
    limit: Optional[float] = 0
    limitEnabled: Optional[bool] = False
    limitType: Optional[str] = "today$"


YC_INFLATION = lambda: ExpenseYearlyChange()                                   # noqa: E731
YC_NONE = lambda: ExpenseYearlyChange(type="none")                             # noqa: E731
YC_INFLATION_PLUS_2 = lambda: ExpenseYearlyChange(type="inflation+", amount=2)  # noqa: E731


class BaseExpense(BaseModel):
    """Fields present on every expense event the UI creates."""
    model_config = {"extra": "allow"}

    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    type: str
    name: str
    title: str
    icon: str
    color: str
    owner: Literal["me", "spouse"] = "me"
    planPath: Literal["expenses"] = "expenses"
    amount: float = 0
    amountType: str = "today$"          # observed: "today$", "grow$" (health-care, medical)
    frequency: str = "yearly"           # observed: "yearly", "monthly", "once"
    frequencyChoices: bool = True
    start: TimeRef = Field(default_factory=lambda: _kw("beforeCurrentYear"))
    end: TimeRef = Field(default_factory=lambda: _kw("endOfPlan", "include"))
    yearlyChange: ExpenseYearlyChange = Field(default_factory=YC_INFLATION)
    key: Optional[float] = None         # random ordering key written by the app; preserve, never invent


class SpendingExpense(BaseExpense):
    """Every non-debt expense also carries a Flexibility setting."""
    spendingType: str = "essential"     # observed: "essential", "discretionary"


