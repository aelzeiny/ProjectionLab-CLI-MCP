    color: str = "orange-lighten-1"
    subtype: Optional[str] = None       # "student-loans" for the Student Loans choice
    frequency: str = "monthly"
    start: TimeRef = Field(default_factory=lambda: _kw("now", "include"))
    end: TimeRef = Field(default_factory=lambda: _kw("never"))
    yearlyChange: ExpenseYearlyChange = Field(default_factory=YC_NONE)
    effectiveDate: TimeRef = Field(default_factory=lambda: _kw("now", "include"))
