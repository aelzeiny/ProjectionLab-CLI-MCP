class NewExpense(BaseModel):
    """Parameters for adding an expense of any verified type to a plan.

    Only `type`, `name` and `amount` are required; every other field defaults to exactly what
    the ProjectionLab "New Expense" dialog would store for that type. `student-loans` is the
    Debt type with the Student Loans subtype/icon.
    """
    type: Annotated[ExpenseType, Field(description="Expense kind (UI choice). See docs/schema.md for what each one stores.")]
    name: Annotated[str, Field(description="Display name.")]
    amount: Annotated[float, Field(description="Amount per `frequency` in today's dollars (for debt: the balance).")]
    owner: Literal["me", "spouse"] = "me"
    frequency: Annotated[Optional[str], Field(description='"monthly", "yearly" or "once". Default depends on type.')] = None
    spendingType: Annotated[Optional[str], Field(description='"essential" or "discretionary". Ignored for debt.')] = None
    start: Optional[TimeRef] = None
    end: Optional[TimeRef] = None
    yearlyChange: Optional[ExpenseYearlyChange] = None
    extra: Annotated[dict[str, Any], Field(description="Any other type-specific fields (e.g. monthlyPayment, interestRate, switchToMarried, taxDeductible).")] = Field(default_factory=dict)
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))

    def to_expense(self) -> BaseExpense:
        kind = self.type
        kwargs: dict[str, Any] = {"id": self.id, "name": self.name, "amount": self.amount, "owner": self.owner}
        if kind == "student-loans":
            kind = "debt"
            kwargs.update(student_loans_defaults())
        model = EXPENSE_MODELS[kind]
        for f in ("frequency", "start", "end", "yearlyChange"):
            if getattr(self, f) is not None:
                kwargs[f] = getattr(self, f)
        if self.spendingType is not None and issubclass(model, SpendingExpense):
            kwargs["spendingType"] = self.spendingType
        kwargs.update(self.extra)
        return model(**kwargs)
